export function ulawToPcm16(sample: number) {
  sample = ~sample;
  const sign = sample & 0x80;
  const exponent = (sample >> 4) & 0x07;
  const mantissa = sample & 0x0f;
  let magnitude = ((mantissa << 3) + BIAS) << exponent;
  magnitude -= BIAS;
  return sign ? -magnitude : magnitude;
}

export function pcm16ToUlaw(sample: number) {
  let pcm = sample;
  const sign = pcm < 0 ? 0x80 : 0;
  if (pcm < 0) pcm = -pcm;
  if (pcm > CLIP) pcm = CLIP;
  pcm += BIAS;
  const exponent = encodeTable[(pcm >> 7) & 0xff];
  const mantissa = (pcm >> (exponent + 3)) & 0x0f;
  return ~(sign | (exponent << 4) | mantissa) & 0xff;
}

export function ulawBufferToPcm16(ulaw: Buffer) {
  const out = new Int16Array(ulaw.length);
  for (let i = 0; i < ulaw.length; i += 1) out[i] = ulawToPcm16(ulaw[i]);
  return out;
}
